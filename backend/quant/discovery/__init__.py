"""Bounded, deterministic strategy discovery with data-snooping safeguards.

1. validate the search config        6. shortlist the best train candidates (max `shortlist`)
2. generate candidates from templates 7. evaluate shortlisted candidates on the validation segment
3. de-duplicate by canonical hash     8. mark candidates unstable when validation contradicts train
4. reject invalid candidates         9. evaluate the untouched test segment only for validated candidates
5. fast backtest on the train segment 10. rank by `rank_v1` on validation metrics, never on test or return alone
"""

from __future__ import annotations

import itertools
import math
import random
import time
from collections.abc import Callable
from dataclasses import dataclass, field
from typing import Annotated, Any, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

from ..data.candles import CandleSeries
from ..engine import BacktestError, resolve_window, run_backtest
from ..strategy_schema.model import StrategyDefinition, canonical_hash
from ..validation import chronological_splits

RANKING_VERSION = "rank_v1"
TEMPLATES = ("ema_cross", "rsi_reversion", "breakout")
MAX_CANDIDATES_LIMIT = 300


class ParamGrid(BaseModel):
    model_config = ConfigDict(extra="forbid")
    ema_fast: list[Annotated[int, Field(ge=2, le=200)]] = [10, 20, 30]
    ema_slow: list[Annotated[int, Field(ge=5, le=400)]] = [50, 100, 200]
    rsi_period: list[Annotated[int, Field(ge=2, le=50)]] = [14]
    rsi_entry: list[Annotated[float, Field(ge=5, le=50)]] = [25, 30, 35]
    rsi_exit: list[Annotated[float, Field(ge=50, le=95)]] = [55, 65]
    breakout_lookback: list[Annotated[int, Field(ge=5, le=200)]] = [20, 40, 60]
    stop_atr: list[Annotated[float, Field(gt=0, le=10)]] = [1.5, 2.5]
    take_profit_r: list[Annotated[float, Field(gt=0, le=10)]] = [2.0, 3.0]


class SearchConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")
    symbol: Literal["BTCUSDT", "ETHUSDT"] = "BTCUSDT"
    timeframe: Literal["15m", "1h", "4h", "1d"] = "1h"
    direction: Literal["long", "short"] = "long"
    templates: Annotated[list[Literal["ema_cross", "rsi_reversion", "breakout"]], Field(min_length=1)] = ["ema_cross"]
    params: ParamGrid = ParamGrid()
    fee_bps: Annotated[float, Field(ge=0, le=100)] = 10.0
    slippage_bps: Annotated[float, Field(ge=0, le=200)] = 5.0
    initial_capital: Annotated[float, Field(gt=0, le=1e9)] = 10_000.0
    max_candidates: Annotated[int, Field(ge=1, le=MAX_CANDIDATES_LIMIT)] = 60
    min_trades: Annotated[int, Field(ge=1, le=1000)] = 30
    max_drawdown: Annotated[float, Field(gt=0, le=1)] = 0.5
    shortlist: Annotated[int, Field(ge=1, le=20)] = 8
    train_fraction: Annotated[float, Field(gt=0.2, lt=0.9)] = 0.6
    validation_fraction: Annotated[float, Field(gt=0.05, lt=0.5)] = 0.2
    max_seconds: Annotated[float, Field(gt=0, le=1800)] = 120.0
    seed: int = 42

    @model_validator(mode="after")
    def _check(self) -> SearchConfig:
        if self.train_fraction + self.validation_fraction >= 0.95:
            raise ValueError("train_fraction + validation_fraction must leave at least 5 % for the test segment.")
        return self


def _base(
    cfg: SearchConfig, name: str, indicators: list[dict], entry: dict, exit_: dict | None, stop: float, tp: float
) -> dict:
    side = cfg.direction
    return {
        "schema_version": "1.0",
        "name": name,
        "description": f"Generated by discovery ({RANKING_VERSION}).",
        "symbols": [cfg.symbol],
        "timeframe": cfg.timeframe,
        "market_type": "futures_sim" if side == "short" else "spot",
        "direction": side,
        "indicators": [*indicators, {"id": "atr14", "type": "atr", "period": 14, "source": "close"}],
        "entry": {side: entry},
        "exit": {side: exit_} if exit_ else {},
        "risk_management": {
            "stop_loss": {"type": "atr", "value": stop, "atr_indicator": "atr14"},
            "take_profit": {"type": "r_multiple", "value": tp},
        },
        "position_sizing": {"type": "risk_percent", "risk_percent": 1.0, "fraction": 1.0},
        "costs": {"fee_bps": cfg.fee_bps, "slippage_bps": cfg.slippage_bps},
    }


def generate_candidates(cfg: SearchConfig) -> list[tuple[str, dict]]:
    p = cfg.params
    up = cfg.direction == "long"
    out: list[tuple[str, dict]] = []
    for tpl in cfg.templates:
        if tpl == "ema_cross":
            for f, s, st, tp in itertools.product(p.ema_fast, p.ema_slow, p.stop_atr, p.take_profit_r):
                ops = ("crosses_above", "crosses_below") if up else ("crosses_below", "crosses_above")
                out.append(
                    (
                        tpl,
                        _base(
                            cfg,
                            f"EMA {f}/{s} SL{st} TP{tp}R",
                            [{"id": "fast", "type": "ema", "period": f}, {"id": "slow", "type": "ema", "period": s}],
                            {"op": ops[0], "left": {"ind": "fast"}, "right": {"ind": "slow"}},
                            {"op": ops[1], "left": {"ind": "fast"}, "right": {"ind": "slow"}},
                            st,
                            tp,
                        ),
                    )
                )
        elif tpl == "rsi_reversion":
            for n, lo, hi, st, tp in itertools.product(
                p.rsi_period, p.rsi_entry, p.rsi_exit, p.stop_atr, p.take_profit_r
            ):
                entry_level, exit_level = (lo, hi) if up else (100 - lo, 100 - hi)
                out.append(
                    (
                        tpl,
                        _base(
                            cfg,
                            f"RSI{n} {entry_level:g}->{exit_level:g} SL{st} TP{tp}R",
                            [{"id": "rsi", "type": "rsi", "period": n}],
                            {
                                "op": "crosses_above" if up else "crosses_below",
                                "left": {"ind": "rsi"},
                                "right": {"value": entry_level},
                            },
                            {"op": "gt" if up else "lt", "left": {"ind": "rsi"}, "right": {"value": exit_level}},
                            st,
                            tp,
                        ),
                    )
                )
        elif tpl == "breakout":
            for n, st, tp in itertools.product(p.breakout_lookback, p.stop_atr, p.take_profit_r):
                ind = {"id": "level", "type": "highest" if up else "lowest", "period": n}
                out.append(
                    (
                        tpl,
                        _base(
                            cfg,
                            f"Breakout {n} SL{st} TP{tp}R",
                            [ind],
                            {"op": "gt" if up else "lt", "left": {"price": "close"}, "right": {"ind": "level"}},
                            None,
                            st,
                            tp,
                        ),
                    )
                )
    return out


@dataclass
class Candidate:
    template: str
    definition: dict
    hash: str
    status: str = "generated"
    rejection_reason: str | None = None
    train: dict[str, Any] = field(default_factory=dict)
    validation: dict[str, Any] = field(default_factory=dict)
    test: dict[str, Any] = field(default_factory=dict)
    cost_stress: dict[str, Any] = field(default_factory=dict)
    flags: list[str] = field(default_factory=list)
    score: float | None = None
    score_parts: dict[str, float] = field(default_factory=dict)


@dataclass
class DiscoveryResult:
    candidates: list[Candidate]
    generated: int
    duplicates: int
    tested: int
    segments: list[dict[str, Any]]
    stopped_early: str | None = None
    ranking_version: str = RANKING_VERSION


KEYS = ("net_return", "max_drawdown", "profit_factor", "win_rate", "trade_count", "expectancy", "expectancy_r")


def _m(
    series: CandleSeries, defn: StrategyDefinition, cfg: SearchConfig, start: int, end: int, mult: float = 1.0
) -> dict[str, Any]:
    r = run_backtest(
        series,
        defn,
        cfg.initial_capital,
        start_index=start,
        end_index=end,
        fee_bps=cfg.fee_bps * mult,
        slippage_bps=cfg.slippage_bps * mult,
    )
    return {k: r.metrics.get(k) for k in KEYS}


def rank_score(c: Candidate) -> tuple[float, dict[str, float]]:
    """rank_v1, computed only from validation metrics plus train/validation consistency and cost stress.

    parts (each 0..1): profit_factor min(PF,3)/3 (0.3), drawdown 1-min(DD/0.5,1) (0.2),
    sample log10(trades)/2 capped (0.15), expectancy_r clamp((R+0.5)/1.5) (0.15),
    consistency min(val_R/train_R,1) if train_R>0 (0.1), cost robustness 1 if positive at 2x costs (0.1).
    """
    v, t = c.validation, c.train
    pf = v.get("profit_factor")
    parts = {
        "profit_factor": min(pf, 3.0) / 3.0 if pf is not None else (0.0 if (v.get("expectancy") or 0) <= 0 else 1.0),
        "drawdown": 1 - min((v.get("max_drawdown") or 0) / 0.5, 1.0),
        "sample": min(math.log10(max(v.get("trade_count") or 0, 1)) / 2, 1.0),
        "expectancy_r": min(max(((v.get("expectancy_r") or 0) + 0.5) / 1.5, 0.0), 1.0),
        "consistency": (
            min(max((v.get("expectancy_r") or 0) / t["expectancy_r"], 0.0), 1.0)
            if (t.get("expectancy_r") or 0) > 0
            else 0.0
        ),
        "cost_robustness": 1.0 if (c.cost_stress.get("net_return") or -1) > 0 else 0.0,
    }
    weights = {
        "profit_factor": 0.3,
        "drawdown": 0.2,
        "sample": 0.15,
        "expectancy_r": 0.15,
        "consistency": 0.1,
        "cost_robustness": 0.1,
    }
    return round(sum(parts[k] * weights[k] for k in parts), 4), parts


def run_discovery(
    series: CandleSeries,
    cfg: SearchConfig,
    *,
    progress: Callable[[int, int], None] | None = None,
    should_cancel: Callable[[], bool] | None = None,
    clock: Callable[[], float] = time.monotonic,
) -> DiscoveryResult:
    if series.symbol != cfg.symbol or series.timeframe != cfg.timeframe:
        raise BacktestError(
            "data_mismatch", f"Data is {series.symbol} {series.timeframe}, search wants {cfg.symbol} {cfg.timeframe}."
        )
    raw = generate_candidates(cfg)
    generated = len(raw)
    rng = random.Random(cfg.seed)
    if len(raw) > cfg.max_candidates:
        raw = rng.sample(raw, cfg.max_candidates)
    seen: set[str] = set()
    cands: list[Candidate] = []
    duplicates = 0
    for tpl, data in raw:
        try:
            defn = StrategyDefinition.model_validate(data)
        except ValueError as exc:
            cands.append(Candidate(tpl, data, "", "rejected", f"invalid: {str(exc)[:200]}"))
            continue
        h = canonical_hash(defn)
        if h in seen:
            duplicates += 1
            continue
        seen.add(h)
        cands.append(Candidate(tpl, defn.model_dump(mode="json", by_alias=True), h))
    valid = [StrategyDefinition.model_validate(c.definition) for c in cands if c.status == "generated"]
    if not valid:
        raise BacktestError("no_candidates", "The search space produced no valid candidates.")
    # One common window for all candidates: start after the longest warm-up so every candidate sees the same bars.
    warm = max(d.warmup_bars() for d in valid)
    start, end = resolve_window(series, valid[0], warm, None)
    if end - start < 300:
        raise BacktestError("insufficient_data", f"Discovery needs at least 300 bars after warm-up, got {end - start}.")
    segs = chronological_splits(start, end, cfg.train_fraction, cfg.validation_fraction)
    train, val, test = segs[0], segs[1], segs[2]
    t0 = clock()
    stopped: str | None = None
    tested = 0
    todo = [c for c in cands if c.status == "generated"]
    for k, c in enumerate(todo):
        if should_cancel and should_cancel():
            stopped = "cancelled"
            break
        if clock() - t0 > cfg.max_seconds:
            stopped = "time_limit"
            break
        defn = StrategyDefinition.model_validate(c.definition)
        try:
            c.train = _m(series, defn, cfg, train.start, train.end)
        except BacktestError as exc:
            c.status, c.rejection_reason = "rejected", f"backtest_error: {exc.code}"
            continue
        tested += 1
        tc = c.train.get("trade_count") or 0
        if tc < cfg.min_trades:
            c.status, c.rejection_reason = "rejected", f"too_few_trades: {int(tc)} < {cfg.min_trades} in train"
        elif (c.train.get("expectancy") or 0) <= 0:
            c.status, c.rejection_reason = "rejected", "non_positive_expectancy_in_train"
        elif (c.train.get("max_drawdown") or 0) > cfg.max_drawdown:
            c.status, c.rejection_reason = "rejected", f"drawdown {c.train['max_drawdown']:.1%} above limit in train"
        if progress:
            progress(k + 1, len(todo))
    passed = [c for c in todo if c.status == "generated" and c.train]
    passed.sort(key=lambda c: (c.train.get("expectancy_r") or 0, c.hash), reverse=True)
    for c in passed[cfg.shortlist :]:
        c.status, c.rejection_reason = "rejected", "not_in_shortlist (ranked by train expectancy_r)"
    for c in passed[: cfg.shortlist]:
        if stopped == "cancelled":
            break
        defn = StrategyDefinition.model_validate(c.definition)
        c.status = "shortlisted"
        c.validation = _m(series, defn, cfg, val.start, val.end)
        c.cost_stress = _m(series, defn, cfg, val.start, val.end, mult=2.0)
        if (c.validation.get("expectancy") or 0) <= 0:
            c.flags.append("unstable: positive in train, not positive in validation")
        if (c.validation.get("trade_count") or 0) < max(5, cfg.min_trades // 3):
            c.flags.append("insufficient: too few validation trades")
        if (c.cost_stress.get("net_return") or -1) <= 0:
            c.flags.append("cost_sensitive: not profitable at 2x costs on validation")
        c.score, c.score_parts = rank_score(c)
        if not c.flags:
            c.status = "validated"
            c.test = _m(series, defn, cfg, test.start, test.end)
            if (c.test.get("expectancy") or 0) <= 0:
                c.flags.append("failed_test: not positive on the untouched test segment")
    return DiscoveryResult(cands, generated, duplicates, tested, [s.to_dict(series) for s in segs], stopped)
